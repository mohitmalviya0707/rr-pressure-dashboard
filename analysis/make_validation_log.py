"""Compile VALIDATION_LOG.md from the JSON/text logs written by the pipeline (no numbers typed by hand)."""
import sys, json, pathlib
OUT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "out")
P = json.loads((OUT / "prep_log.json").read_text()); V = json.loads((OUT / "validation_engine.json").read_text())
S = json.loads((OUT / "scenario_summary.json").read_text())
L = ["# Validation log (generated by make_validation_log.py from the pipeline's own outputs)", ""]
def sec(t, obj): L.extend([f"## {t}", "```json", json.dumps(obj, indent=1, default=str), "```", ""])
sec("Scope and match filters (prep.py)", {k: P[k] for k in ("scope", "match_filter", "deliveries_raw", "super_over_deliveries_removed_in_scope", "deliveries_used", "matches_used", "by_format_matches") if k in P})
sec("Extras audit and assumptions (prep.py)", P.get("extras_audit"))
sec("Win probability: 5-fold out-of-fold validation grouped by match (prep.py)", {k: v for k, v in P["validation_wp_out_of_fold"].items()})
sec("Recalibration parameters per format x innings", P.get("recalibration_logit_a_b"))
sec("Markov DP vs Monte-Carlo simulation", P.get("validation_dp_monte_carlo"))
sec("Expected remaining runs: model vs actual", P.get("validation_expected_runs"))
sec("Wicket run value: model vs empirical", {"validation": P.get("validation_wicket_value"), "by_phase": P.get("wicket_value_by_phase")})
sec("Score reconstruction vs official result margins", P.get("validation_score_reconstruction"))
sec("Primary model and 10 scenarios (picks.py)", S)
sec("Final selection: 600-run stress grid summary (stress.py, final_select.py)", json.loads((OUT / "selection_summary.json").read_text()))
sec("Engine validation: shrinkage stability, opponent adjustment, extras sensitivity, innings breakdown (validate.py)", V)
for name, title in (("audit_log.txt", "Independent audit (audit.py)"), ("crosscheck_log.txt", "Dashboard (browser JS) vs Python cross-check (lab/crosscheck.py)")):
    f = OUT / name
    L.extend([f"## {title}", "```", f.read_text().rstrip() if f.exists() else "(not run yet)", "```", ""])
(OUT / "VALIDATION_LOG.md").write_text("\n".join(L)); print("wrote", OUT / "VALIDATION_LOG.md")
