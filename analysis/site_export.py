"""Export summary results for the public dashboard (python site_export.py out <site_dir>).
Player-level model outputs only; no ball-by-ball rows."""
import sys, json, pathlib, numpy as np, pandas as pd
sys.path.insert(0, str(pathlib.Path(__file__).parent)); import engine
OUT, SITE = sys.argv[1], pathlib.Path(sys.argv[2])
b = engine.load(f"{OUT}/balls_prepped.csv"); r = engine.run(b)
D = json.load(open(f"{OUT}/deck.json")); fp = pd.read_csv(f"{OUT}/final_picks.csv")
SC = D["scen_names"] if "scen_names" in D else None
E = {k: pd.read_csv(f"{OUT}/rankings_{k}_all_eligible.csv").set_index("player_id") for k in ("batters", "bowlers")}
scen_cols = [c for c in E["batters"].columns if c.startswith("rank: ")]
players = []
for kind, key, lst in (("Batter", "B", "batters"), ("Bowler", "W", "bowlers")):
    T = r[key]; S = pd.read_csv(f"{OUT}/selection_{lst}_all.csv").set_index("player_id")
    picks = fp[fp.list == lst].set_index("player_id")
    for pid, g in T.iterrows():
        e = E[lst].loc[pid]
        rec = dict(id=int(pid), name=E[lst].loc[pid, "player"], kind=kind, nP=int(g.nP), mP=int(g.mP), pos=int(g.pos), level=float(g.level), base=float(g.base),
                   delta=float(g.delta), cons=float(g.cons), rank=int(g["rank"]),
                   scen=[None if pd.isna(e[c]) else int(e[c]) for c in scen_cols],
                   stab=round(float(S.loc[pid, "combined"]), 2) if pid in S.index else 0.0, stabRank=int(S.loc[pid, "final_rank"]) if pid in S.index else None,
                   pick=int(picks.loc[pid, "rank"]) if pid in picks.index else None)
        if kind == "Batter": rec.update(srP=round(100 * g.rP / g.nP, 1), srQ=round(100 * g.rQ / g.nQ, 1) if g.nQ else None, outs=int(g.oP))
        else: rec.update(ecoP=round(6 * g.rP / g.nP, 2), ecoQ=round(6 * g.rQ / g.nQ, 2) if g.nQ else None, wkts=int(g.oP))
        players.append(rec)
detail = {}
for kind, lst in (("bat", "Batter"), ("bowl", "Bowler")):
    for e in D[kind]:
        detail[str(e["id"])] = dict(nat=e["nat"], ipl26=e.get("ipl26"), role=e["role_txt"], contrib=e["contrib"], phase=e["phase"],
            split={k: (None if v["value"] is None else round(v["value"], 1), v["n"]) for k, v in e["split_A"].items()},
            style=e.get("style") or e.get("hand"), srP=e.get("srP"), srQ=e.get("srQ"), brP=e.get("batRunsOverP"), brQ=e.get("batRunsOverQ"))
P = json.load(open(f"{OUT}/prep_log.json")); S = json.load(open(f"{OUT}/scenario_summary.json")); A = open(f"{OUT}/audit_log.txt").read().splitlines()
O = P["validation_wp_out_of_fold"]
meta = dict(matches=P["matches_used"], deliveries=P["deliveries_used"], pressure=S["primary"]["pressure_deliveries"], settings=600,
            audit=sum(l.startswith("PASS") for l in A), auc_chase=O["chase_all"]["auc"], auc_first=O["first_innings_all"]["auc"], ece=O["chase_all"]["ece"],
            rho_bat=S["primary"]["split_half_bat"][0], rho_bowl=S["primary"]["split_half_bowl"][0], mae=P["validation_score_reconstruction"]["margin_mae_runs"],
            kB=S["primary"]["kB"], kW=S["primary"]["kW"], weights=[0.6, 0.25, 0.15], min_balls=120, min_matches=8,
            scen_names=[c.replace("rank: ", "") for c in scen_cols], by_over=D["by_over"], by_over_A=D["by_over_A"], grid_rho=D["grid_rho"],
            cal=O["chase_all"].get("calibration"))
(SITE / "data").mkdir(parents=True, exist_ok=True)
(SITE / "data" / "results.js").write_text("// Summary results only: player-level model outputs, no ball-by-ball data. Generated by analysis/site_export.py\nwindow.RESULTS = "
    + json.dumps(dict(players=players, detail=detail, meta=meta), separators=(",", ":")) + ";\n")
pd.DataFrame(players).drop(columns=["scen"]).to_csv(SITE / "data" / "players.csv", index=False)
print(len(players), "players exported")
